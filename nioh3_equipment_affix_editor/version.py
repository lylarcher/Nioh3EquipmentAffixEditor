"""Version and build information for Nioh 3 Equipment Affix Editor.

Four facts are always reported, in this order:

1. ``commit``   -- the **last 8 characters** of the git commit id.
2. ``built_from`` / ``crypto_exe`` -- where this build came from: the project
   root and the crypto executable path at build time.  The user-visible banner
   reports the *run-time* counterparts (see ``version_lines``) and only mentions
   the build-time root when the two differ.
3. ``built_at`` -- the local build timestamp (ISO-8601 with UTC offset).
4. ``language`` -- the Python implementation/runtime the build targets.

Two sources are consulted, in this order:

* ``nioh3_equipment_affix_editor/_buildinfo.py`` -- generated by
  ``tools/make_build_info.py`` (called from ``build.ps1``).  This is what a
  packaged/distributed copy reports, since it carries frozen values.
* Live git interrogation of the source tree -- used when running from a
  checkout that has not been built; every unknown field degrades to
  ``"unknown"`` instead of raising, because version display must never break
  the application.
"""

from __future__ import annotations

import subprocess
from dataclasses import dataclass
from pathlib import Path

from . import paths

__all__ = [
    "BUILD_SCHEMA",
    "DEFAULT_CRYPTO_EXE",
    "PROJECT_ROOT",
    "UNKNOWN",
    "BuildInfo",
    "commit_short",
    "short_commit",
    "version_banner",
    "version_info",
    "version_lines",
    "version_title",
    "__version__",
]

__version__ = "0.1.0"

BUILD_SCHEMA = "nioh3-accessory-editor-build/v1"
PROJECT_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_CRYPTO_EXE = PROJECT_ROOT / "bin" / "Nioh_Savefile_decrypt.exe"
UNKNOWN = "unknown"
SHORT_COMMIT_LENGTH = 8

#: How long each user-visible line of the banner may be when generated.
_BANNER_WIDTH = 78

_CACHE: "BuildInfo | None" = None


def short_commit(commit: str | None) -> str:
    """Return the LAST ``SHORT_COMMIT_LENGTH`` characters of a commit id.

    Using the tail (not the usual git prefix) is a deliberate project
    convention, so the shortened id stays recognisable next to the full hash.
    Anything shorter is returned unchanged; ``None``/empty becomes ``unknown``.
    """
    if not commit:
        return UNKNOWN
    text = str(commit).strip()
    if not text:
        return UNKNOWN
    return text[-SHORT_COMMIT_LENGTH:]


# Public alias with the naming used by the build tooling.
commit_short = short_commit


@dataclass(frozen=True, slots=True)
class BuildInfo:
    """One immutable snapshot of version/build facts."""

    version: str
    commit: str
    commit_full: str
    branch: str
    dirty: bool
    built_at: str
    built_from: str
    crypto_exe: str
    crypto_exe_sha256: str
    language: str
    python_version: str
    source: str
    build_schema: str = BUILD_SCHEMA

    @property
    def commit_is_known(self) -> bool:
        return self.commit not in ("", UNKNOWN)

    @property
    def dirty_suffix(self) -> str:
        return " (工作区有未提交改动)" if self.dirty else ""

    def as_dict(self) -> dict[str, object]:
        return {
            "schema": self.build_schema,
            "component": "Nioh3EquipmentAffixEditor",
            "version": self.version,
            "commit": self.commit,
            "commit_full": self.commit_full,
            "branch": self.branch,
            "worktree_dirty": self.dirty,
            "built_at": self.built_at,
            "built_from": self.built_from,
            "crypto_exe": self.crypto_exe,
            "crypto_exe_sha256": self.crypto_exe_sha256,
            "language": self.language,
            "python_version": self.python_version,
            "info_source": self.source,
        }



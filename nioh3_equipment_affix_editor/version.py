def _run_git(arguments: list[str]) -> str | None:
    """Run git in the project root, returning ``None`` when unavailable."""
    try:
        result = subprocess.run(
            ["git", *arguments],
            cwd=str(PROJECT_ROOT),
            capture_output=True,
            text=True,
            timeout=5,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    if result.returncode != 0:
        return None
    return result.stdout.strip()


def _git_info() -> dict[str, object] | None:
    commit_full = _run_git(["rev-parse", "HEAD"])
    if not commit_full:
        return None
    status = _run_git(["status", "--porcelain"])
    return {
        "commit_full": commit_full,
        "commit": short_commit(commit_full),
        "branch": _run_git(["rev-parse", "--abbrev-ref", "HEAD"]) or UNKNOWN,
        "dirty": bool(status) if status is not None else False,
    }


def _frozen_info() -> dict[str, object] | None:
    """Read the generated ``_buildinfo`` module when the build created one."""
    try:
        from . import _buildinfo  # type: ignore[attr-defined]  # noqa: PLC0415
    except ImportError:
        return None
    return {
        "version": getattr(_buildinfo, "VERSION", __version__),
        "commit": getattr(_buildinfo, "COMMIT", UNKNOWN),
        "commit_full": getattr(_buildinfo, "COMMIT_FULL", UNKNOWN),
        "branch": getattr(_buildinfo, "BRANCH", UNKNOWN),
        "dirty": bool(getattr(_buildinfo, "DIRTY", False)),
        "built_at": getattr(_buildinfo, "BUILT_AT", UNKNOWN),
        "built_from": getattr(_buildinfo, "BUILT_FROM", str(PROJECT_ROOT)),
        "crypto_exe": getattr(_buildinfo, "CRYPTO_EXE", str(DEFAULT_CRYPTO_EXE)),
        "crypto_exe_sha256": getattr(_buildinfo, "CRYPTO_EXE_SHA256", UNKNOWN),
        "language": getattr(_buildinfo, "LANGUAGE", UNKNOWN),
        "python_version": getattr(_buildinfo, "PYTHON_VERSION", UNKNOWN),
    }


def _runtime_language() -> str:
    import platform

    implementation = platform.python_implementation()
    version = platform.python_version()
    return f"{implementation} {version} (仅标准库 / stdlib only)"


def version_info(*, refresh: bool = False) -> BuildInfo:
    """Return the current build/version facts (cached)."""
    global _CACHE
    if _CACHE is not None and not refresh:
        return _CACHE

    frozen = _frozen_info()
    # A built executable has no checkout to interrogate (and no git binary in
    # reach), so its identity comes from the generated module only.
    live = None if paths.is_frozen() else _git_info()
    fields: dict[str, object] = {
        "version": __version__,
        "commit": UNKNOWN,
        "commit_full": UNKNOWN,
        "branch": UNKNOWN,
        "dirty": False,
        "built_at": UNKNOWN,
        "built_from": str(paths.application_root()),
        "crypto_exe": str(paths.default_crypto_exe()),
        "crypto_exe_sha256": UNKNOWN,
        "language": _runtime_language(),
        "python_version": _python_version(),
        "source": "fallback",
    }
    if live is not None:
        fields.update(live)
        fields["built_at"] = UNKNOWN  # a checkout has no build time
        fields["source"] = "git"
    if frozen is not None:
        fields.update({key: value for key, value in frozen.items()
                       if value not in (None, "")})
        fields["source"] = "build"
    if paths.is_frozen() and frozen is None:
        # Frozen without generated build info must still not claim to be a
        # checkout: report the executable itself as the source.
        fields["source"] = "frozen"
        fields["built_from"] = str(paths.application_root())

    _CACHE = BuildInfo(**fields)  # type: ignore[arg-type]
    return _CACHE


def _python_version() -> str:
    import platform

    return platform.python_version()


def reset_cache() -> None:
    """Drop the cached :class:`BuildInfo` (used by tests)."""
    global _CACHE
    _CACHE = None



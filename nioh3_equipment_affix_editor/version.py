def _take(text: str, budget: int, *, from_start: bool) -> str:
    """Longest prefix/suffix of ``text`` that fits ``budget`` display columns."""
    import unicodedata

    chars = text if from_start else reversed(text)
    kept: list[str] = []
    used = 0
    for char in chars:
        step = 2 if unicodedata.east_asian_width(char) in "WF" else 1
        if used + step > budget:
            break
        kept.append(char)
        used += step
    if not from_start:
        kept.reverse()
    return "".join(kept)


def _elide(text: str, width: int = _BANNER_WIDTH, *, enabled: bool = True) -> str:
    """Shorten ``text`` to ``width`` display columns, keeping the tail visible.

    The tail is what identifies the file (``...\\bin\\Nioh_Savefile_decrypt.exe``),
    so the abbreviation keeps a short head plus as much of the end as fits; a
    leading-only cut would hide exactly the part the reader needs.  ``enabled=False``
    returns the path untouched — the diagnostic ``BUILD-INFO.txt`` records full paths.
    """
    if not enabled or _display_width(text) <= width:
        return text
    budget = max(0, width - 3)
    head_budget = min(24, budget // 3)
    tail_budget = budget - head_budget
    return _take(text, head_budget, from_start=True) + "..." + _take(
        text, tail_budget, from_start=False)


def _display_width(text: str) -> int:
    """Terminal columns used by ``text`` (CJK/full-width characters count 2)."""
    import unicodedata

    return sum(2 if unicodedata.east_asian_width(char) in "WF" else 1
               for char in text)


def _pad_to(text: str, width: int) -> str:
    """Left-align ``text`` in a field ``width`` *display columns* wide."""
    return text + " " * max(0, width - _display_width(text))


def version_lines(
    info: BuildInfo | None = None,
    *,
    location: str | Path | None = None,
    crypto_exe: str | Path | None = None,
    elide: bool = True,
) -> tuple[str, ...]:
    """Human-readable version block, one entry per line.

    Field labels are padded by display width so the colons line up even in a
    mixed ASCII/CJK terminal.

    ``来源`` and ``加密组件`` are resolved **at run time**: the directory the
    running executable actually sits in and the crypto component it reads from
    there, so copying the exe elsewhere (or building on another machine) never
    prints a stale path.  The build-time project root is deliberately **not**
    shown anywhere: it names the machine the build ran on, which is of no use to
    whoever is running the editor.  It stays recorded in ``BUILD-INFO.txt`` for
    diagnosis.  ``location``/``crypto_exe`` override the resolution (tests only).
    """
    if info is None:
        info = version_info()
    label_width = 10
    built_at = info.built_at if info.built_at != UNKNOWN else "未构建（源码运行）"
    runtime_root = Path(location) if location is not None else paths.application_root()
    runtime_crypto = (Path(crypto_exe) if crypto_exe is not None
                      else paths.default_crypto_exe())
    lines = [
        f"Nioh 3 Equipment Affix Editor v{info.version}",
        f"{_pad_to('commit', label_width)}: {info.commit}{info.dirty_suffix}",
        f"{_pad_to('来源', label_width)}: {_elide(str(runtime_root), enabled=elide)}",
        f"{_pad_to('加密组件', label_width)}: {_elide(str(runtime_crypto), enabled=elide)}",
        f"{_pad_to('构建时间', label_width)}: {built_at}",
        f"{_pad_to('语言', label_width)}: {info.language}",
    ]
    return tuple(lines)


def version_banner(info: BuildInfo | None = None) -> str:
    """Multi-line banner used by ``--version``, the GUI and build reports."""
    return "\n".join(version_lines(info))


def version_title(info: BuildInfo | None = None) -> str:
    """Compact single-line form for window titles and status bars."""
    if info is None:
        info = version_info()
    built = info.built_at[:19].replace("T", " ") if info.built_at != UNKNOWN else "未构建"
    return f"v{info.version} · commit {info.commit} · 构建 {built}"

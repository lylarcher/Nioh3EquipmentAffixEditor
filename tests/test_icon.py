class BuiltExecutableTests(unittest.TestCase):
    """Only runs when a *current* built exe is present.

    A ``dist/`` exe older than ``assets/`` legitimately carries the previous
    artwork; ``build.ps1`` re-checks the freshly built exe with
    ``tools/check_exe_icon.py`` before it is shipped, so the assertion here is
    skipped instead of failing on a stale artifact.
    """

    def setUp(self) -> None:
        if not DIST_EXE.is_file():
            self.skipTest("dist/Nioh3EquipmentAffixEditor.exe 不存在")
        for asset in ASSETS.iterdir():
            if asset.is_file() and asset.stat().st_mtime > DIST_EXE.stat().st_mtime:
                self.skipTest(
                    f"dist 中的 exe 早于 {asset.name}；构建时会用 "
                    "tools/check_exe_icon.py 重新校验")

    def test_exe_carries_every_icon_size(self) -> None:
        report = check_exe_icon.inspect(DIST_EXE, ASSETS / make_icon.ICON_NAME)
        self.assertEqual(report["sizes"], sorted(make_icon.ICON_SIZES))
        self.assertEqual(report["mismatched_sizes"], [],
                         "dist 中的 exe 图标与当前 assets/ 不一致")
        self.assertEqual(report["identical_images"], report["expected_images"])

class GroupIconParserTests(unittest.TestCase):
    def test_reads_sizes_including_256(self) -> None:
        blob = struct.pack("<HHH", 0, 1, 2)
        blob += struct.pack("<BBBBHHIH", 16, 16, 0, 0, 1, 32, 100, 1)
        blob += struct.pack("<BBBBHHIH", 0, 0, 0, 0, 1, 32, 200, 2)  # 0 means 256
        self.assertEqual(check_exe_icon.icon_sizes_from_group(blob), [16, 256])

    def test_rejects_a_non_icon_resource(self) -> None:
        blob = struct.pack("<HHH", 0, 2, 0)
        with self.assertRaises(check_exe_icon.PeError):
            check_exe_icon.icon_sizes_from_group(blob)

    def test_rejects_a_file_without_pe_signature(self) -> None:
        with self.assertRaises(check_exe_icon.PeError):
            check_exe_icon._sections(b"not a pe file at all")


def _write_temp_ico(data: bytes) -> Path:
    import tempfile

    handle = tempfile.NamedTemporaryFile(suffix=".ico", delete=False)
    handle.write(data)
    handle.close()
    path = Path(handle.name)
    import atexit

    atexit.register(path.unlink, missing_ok=True)
    return path


def _read_entries(data: bytes) -> list[tuple[int, int, bytes]]:
    return [(size, blob_size, blob)
            for size, blob_size, blob in check_exe_icon.read_ico_entries(
                _write_temp_ico(data))]



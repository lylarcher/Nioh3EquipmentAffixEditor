def _load_payload(path: Path, what: str, *,
                  list_key: str = "affixes") -> dict:
    if not path.is_file():
        raise AffixError(f"缺少{what}文件 {path}；请先运行 tools/build_affix_db.py 生成")
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise AffixError(f"{what}文件无法解析：{path}（{error}）") from error
    if not isinstance(payload, dict):
        raise AffixError(f"{what}文件格式错误：{path} 顶层必须是对象")
    raw_entries = payload.get(list_key)
    if not isinstance(raw_entries, list) or not raw_entries:
        raise AffixError(f"{what}文件没有 {list_key} 列表：{path}")

    declared = payload.get("count")
    if isinstance(declared, int) and declared != len(raw_entries):
        raise AffixError(
            f"{what}文件自述 {declared} 条但实际包含 {len(raw_entries)} 条：{path}"
        )
    return payload


def _entries_from_payload(payload: dict, path: Path) -> list[AffixEntry]:
    entries: list[AffixEntry] = []
    for index, item in enumerate(payload["affixes"]):
        where = f"第 {index + 1} 条"
        if not isinstance(item, dict):
            raise AffixError(f"{where}: 词条条目必须是对象")
        name = item.get("name")
        category = item.get("category")
        if not isinstance(name, str) or not name.strip():
            raise AffixError(f"{where}: 缺少词条名称")
        if not isinstance(category, str):
            raise AffixError(f"{where}: 缺少词条类别")
        entries.append(
            AffixEntry(
                effect_id=_require_uint32(item, "effect_id", where),
                value=_require_uint32(item, "value", where),
                flags=_require_uint32(item, "flags", where),
                name=name.strip(),
                category=category.strip(),
                values=_optional_value_set(item, where),
        value_min=_optional_uint32(item, "value_min", where),
                value_max=_optional_uint32(item, "value_max", where),
            )
        )
    return entries


def _optional_value_set(item: dict, where: str) -> tuple[int, ...] | None:
    """Read an explicit 数值集合, rejecting anything that is not ascending ints."""
    raw = item.get("values")
    if raw is None:
        return None
    if not isinstance(raw, list) or not raw:
        raise AffixError(f"{where}: values 必须是非空数组")
    numbers = []
    for value in raw:
        number = _require_uint32({"v": value}, "v", where)
        numbers.append(number)
    if numbers != sorted(set(numbers)):
        raise AffixError(f"{where}: values 必须去重且升序")
    return tuple(numbers)


def _optional_uint32(item: dict, key: str, where: str) -> int | None:
    """Read an optional unsigned int; a present-but-invalid value is an error."""
    if key not in item or item[key] is None:
        return None
    return _require_uint32(item, key, where)


def save_catalog(
    entries: list[AffixEntry],
    path: Path = DEFAULT_CATALOG,
    *,
    source: str = "",
    conflicts: list[str] | None = None,
    schema: str = CATALOG_SCHEMA,
    default_source: str = "仁王3词条装备库v2.21.xlsx / 饰品词条",
) -> None:
    """Write entries as the JSON catalog (used by the build tool)."""
    seen: set[int] = set()
    for entry in entries:
        if entry.effect_id in seen:
            raise AffixError(f"拒绝写出含重复词条 ID 的词条库：{entry.effect_id:#x}")
        seen.add(entry.effect_id)
    payload = {
        "schema": schema,
        "count": len(entries),
        "source": source or default_source,
        "conflicts": conflicts or [],
        "affixes": [
            {
                "effect_id": entry.effect_id,
                "value": entry.value,
                "flags": entry.flags,
                "name": entry.name,
                "category": entry.category,
                **({"values": list(entry.values)} if entry.values else {}),
            **({"value_min": entry.value_min, "value_max": entry.value_max}
                   if entry.has_value_range else {}),
            }
            for entry in entries
        ],
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    # newline="\n": the catalog is a committed text file, so its bytes must not
    # depend on the platform that regenerated it.
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
                    encoding="utf-8", newline="\n")



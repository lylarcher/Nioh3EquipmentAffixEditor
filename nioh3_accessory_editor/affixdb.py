"""Accessory affix (词条) catalog built from the 仁王3词条装备库v2.21.xlsx.

The catalog is a JSON file (``data/accessory_affixes.json``) generated by
``tools/build_affix_db.py`` from the workbook's 饰品词条 sheet (309 rows).
Each entry records:

* ``effect_id`` — u32 little-endian value from bytes 0..3 of the 词条代码.
* ``value`` — u32 value from bytes 4..7 (the nominal display value).
* ``flags`` — metadata bits: 0x40 = 同名固定, 0x04 = 星号.
* ``name`` — display name including the (同名固定)/(星) prefix.
* ``category`` — the 类别 column (造成伤害/精力减少/...).

``AffixDb`` provides id->name lookup and validation used by the editor to fail
closed on anything outside the accessory table.  A catalog containing duplicate
effect ids is rejected outright: the editor resolves edits by id, so an
ambiguous id could silently apply the wrong value.
"""


DEFAULT_CATALOG = default_catalog_path()
CATALOG_SCHEMA = "nioh3-accessory-affixes/v1"

#: 恩宠 / 套装组合 names.  These ids are **not** legal accessory affixes (armour
#: carries 套装 codes), so they live in their own table used for display only:
#: every real accessory ends with one of them (e.g. 稻荷神的恩宠 on a 龙笛), and
#: without the table the editor could only call that slot an unknown affix.
DEFAULT_GRACE_CATALOG = default_grace_path()
GRACE_CATALOG_SCHEMA = "nioh3-grace-affixes/v1"

#: 归属 values that describe a *changeable* 恩宠 (a name ending in 的恩宠).  The
#: 套装 kinds are listed in the same table but must never be written: the game
#: keeps item-specific 套装 effects (e.g. 怨恨盖世) in a different family byte.
GRACE_KINDS = ("恩宠", "上位恩宠")

#: The 饰品 rows of 物品总目录 — what an accessory *is* (its 种类), keyed by the
#: per-item id the record header carries in v2.21.  Display only, like the grace
#: table: the ids live in a different space from 词条 ids, and nothing here may
#: ever authorise a write.  Measured on the reference save: 212 of 213
#: accessories resolve to one of these 88 ids.
DEFAULT_ITEM_CATALOG = default_items_path()
ITEM_CATALOG_SCHEMA = "nioh3-accessory-items/v1"

#: 魂核 (soul cores) have their own affix pool: 绘卷-魂核词条, 种类 = 魂核 → 287 ids in
#: v2.21, of which exactly one id also appears in the 饰品词条 table.  A 魂核 has no
#: 恩宠/套装 affix, so its edits are gated by this table (and its own item table).
DEFAULT_SOUL_CATALOG = default_soul_catalog_path()
SOUL_CATALOG_SCHEMA = "nioh3-soul-affixes/v1"

#: 魂核 rows of 物品总目录 (大类 = 魂核, 83 ids in v2.21) — what a 魂核 *is*.
DEFAULT_SOUL_ITEM_CATALOG = default_soul_items_path()
SOUL_ITEM_CATALOG_SCHEMA = "nioh3-soul-items/v1"

# Metadata flag bits decoded from the 词条代码 byte layout:
# byte 9 bit6 = 固定 (同名固定 variants carry 0x43/0x45/0x46), byte 10 bit2 = 星.
FLAG_FIXED = 0x40
FLAG_STAR = 0x04

EMPTY_EFFECT_ID = 0xFFFFFFFF
_UINT32_MAX = 0xFFFFFFFF


class AffixError(ValueError):
    """Raised when an affix is not in the legal accessory catalog."""


@dataclass(frozen=True, slots=True)
class AffixEntry:
    effect_id: int
    value: int
    flags: int
    name: str
    category: str
    #: Legal value span of this affix, from the workbook's own value table
    #: (全词条数值 取值集合 for 饰品, 数值区间/数值集合 for 魂核).  ``None`` means the
    #: workbook gave no span, and then the editor refuses to write any value other
    #: than the catalog's own — guessing a range would be exactly the kind of
    #: unverified write this tool must not do.  Measured on the reference save's
    #: save: all 807 catalogued accessory slots hold a value inside their span.
    value_min: int | None = None
    value_max: int | None = None
    #: The workbook's own 数值集合 when it is **not** every integer of the span (e.g.
    #: 绿色星号词条 0x248c allows 470,472,475,…,520).  ``None`` means "the whole span",
    #: which is what every other catalog row is (measured).
    values: tuple[int, ...] | None = None

    @property
    def is_fixed(self) -> bool:
        return bool(self.flags & FLAG_FIXED)

    @property
    def is_star(self) -> bool:
        return bool(self.flags & FLAG_STAR)

    @property
    def has_value_range(self) -> bool:
        return self.value_min is not None and self.value_max is not None

    def allows_value(self, value: int) -> bool:
        """Whether ``value`` is one the workbook lists for this affix.

        An explicit 数值集合 wins over the span: the green sheet has rows whose legal
        values step by 2.5 (470, 472, 475, …), and writing 471 or 473 would be a
        value the game never rolls.
        """
        if self.values:
            return value in self.values
        if not self.has_value_range:
            return False
        return bool(self.value_min <= value <= self.value_max)  # type: ignore[operator]

    def describe_value_range(self) -> str:
        if self.values:
            listed = "、".join(str(value) for value in self.values)
            if len(self.values) <= 8:
                return f"取值 {listed}"
            return (f"{self.value_min}..{self.value_max} 共 {len(self.values)} 个取值"
                    f"（{self.values[0]}、{self.values[1]}…{self.values[-1]}）")
        if not self.has_value_range:
            return "数值区间未知（原始表未给出）"
        if self.value_min == self.value_max:
            return f"固定值 {self.value_min}"
        return f"{self.value_min}..{self.value_max}"

    @property
    def label(self) -> str:
        """Stable combo-box label: ``0x0b32 (同名固定)守护灵技的伤害 +20.0%``."""
        return f"{self.effect_id:#06x} {self.name}"


class AffixDb:
    """Immutable catalog of legal accessory affixes with id lookups."""

    __slots__ = ("_entries", "_by_id", "catalog_path")

    def __init__(
        self,
        entries: list[AffixEntry] | None = None,
        catalog_path: Path = DEFAULT_CATALOG,
    ) -> None:
        self.catalog_path = catalog_path
        self._entries = tuple(entries) if entries is not None else tuple(load_catalog(catalog_path))
        by_id: dict[int, AffixEntry] = {}
        for entry in self._entries:
            if entry.effect_id in by_id:
                raise AffixError(
                    f"词条库存在重复的词条 ID {entry.effect_id:#x}；"
                    "请重新生成词条库（tools/build_affix_db.py）"
                )
            by_id[entry.effect_id] = entry
        self._by_id = by_id

    @classmethod
    def from_file(cls, catalog_path: Path = DEFAULT_CATALOG) -> "AffixDb":
        return cls(catalog_path=catalog_path)

    def __len__(self) -> int:
        return len(self._entries)

    def __contains__(self, effect_id: object) -> bool:
        return effect_id in self._by_id

    def lookup(self, effect_id: int) -> AffixEntry | None:
        return self._by_id.get(effect_id)

    def is_legal(self, effect_id: int) -> bool:
        return effect_id in self._by_id

    def require(self, effect_id: int) -> AffixEntry:
        entry = self.lookup(effect_id)
        if entry is None:
            raise AffixError(f"词条 {effect_id:#010x} 不在合法的饰品词条表中")
        return entry

    def describe(self, effect_id: int) -> str:
        entry = self.lookup(effect_id)
        if entry is None:
            return f"未知词条 {effect_id:#010x}"
        return entry.name

    def all(self) -> tuple[AffixEntry, ...]:
        return self._entries

    def by_category(self, category: str | None = None) -> tuple[AffixEntry, ...]:
        if category is None:
            return self._entries
        return tuple(entry for entry in self._entries if entry.category == category)

    def categories(self) -> tuple[str, ...]:
        seen: list[str] = []
        for entry in self._entries:
            if entry.category not in seen:
                seen.append(entry.category)
        return tuple(seen)

    def labels(self) -> tuple[str, ...]:
        """Combo-box labels, prefixed with the empty-slot choice."""
        return ("(空)",) + tuple(entry.label for entry in self._entries)

    @staticmethod
    def _token_matches(entry: AffixEntry, token: str) -> bool:
        """One keyword against one entry: name, category, or id text."""
        token = token.lower()
        compact = token.replace(" ", "")
        return bool(
            token in entry.name.lower()
            or token in entry.category.lower()
            or compact in entry.name.lower().replace(" ", "")
            or compact in f"{entry.effect_id:#x}".lower()
        )

    def search(self, keyword: str, *, limit: int = 0) -> tuple[AffixEntry, ...]:
        """Every entry matching **all** keywords, which are separated by spaces.

        ``星 恢复`` therefore means "the name must contain 星 *and* 恢复", which is
        how a list of 308 catalogued affixes stays usable.  A single keyword behaves
        exactly as before.  Typing a keyword must never silently pick one affix: the
        caller shows the whole match list (empty, one, or many) and the user chooses
        from it.  A blank keyword matches nothing, so an empty search box can never
        be mistaken for "everything".
        """
        tokens = [token for token in keyword.replace("\u3000", " ").split() if token]
        if not tokens:
            return ()
        matches = [entry for entry in self._entries
                   if all(self._token_matches(entry, token) for token in tokens)]
        if limit > 0:
            return tuple(matches[:limit])
        return tuple(matches)


def _require_uint32(payload: dict[str, object], key: str, where: str) -> int:
    value = payload.get(key)
    if not isinstance(value, int) or isinstance(value, bool):
        raise AffixError(f"{where}: 字段 {key} 必须是整数，实际 {value!r}")
    if not 0 <= value <= _UINT32_MAX:
        raise AffixError(f"{where}: 字段 {key} 超出 uint32 范围：{value}")
    return value


def load_catalog(path: Path = DEFAULT_CATALOG) -> list[AffixEntry]:
    """Load entries from the generated JSON catalog, validating every field."""
    payload = _load_payload(path, "词条库")
    return _entries_from_payload(payload, path)


def load_grace_catalog(path: Path = DEFAULT_GRACE_CATALOG) -> list[AffixEntry]:
    """Load the 恩宠/套装 name table (display only, never used for legality)."""
    payload = _load_payload(path, "恩宠/套装名表")
    return _entries_from_payload(payload, path)


def load_soul_catalog(path: Path = DEFAULT_SOUL_CATALOG) -> list[AffixEntry]:
    """Load the legal 魂核 affix table (绘卷-魂核词条, 种类=魂核)."""
    payload = _load_payload(path, "魂核词条库")
    return _entries_from_payload(payload, path)


def load_soul_item_catalog(path: Path = DEFAULT_SOUL_ITEM_CATALOG) -> list[ItemEntry]:
    """Load the 魂核 item table (物品总目录 大类=魂核; display only)."""
    payload = _load_payload(path, "魂核物品种类表", list_key="items")
    raw_items = payload["items"]
    entries: list[ItemEntry] = []
    for index, raw in enumerate(raw_items):
        where = f"{path} 第 {index + 1} 条"
        if not isinstance(raw, dict):
            raise AffixError(f"{where} 必须是对象")
        item_id = _require_uint32(raw, "item_id", where)
        name = raw.get("name")
        category = raw.get("category", "")
        if not isinstance(name, str) or not name.strip():
            raise AffixError(f"{where} 缺少 name")
        if not isinstance(category, str):
            raise AffixError(f"{where} 的 category 必须是字符串")
        entries.append(ItemEntry(item_id=item_id, name=name.strip(),
                                 category=category.strip()))
    return entries



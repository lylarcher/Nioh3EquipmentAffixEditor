@dataclass(frozen=True, slots=True)
class ItemEntry:
    """One 饰品 row of 物品总目录: what an accessory *is*, not what it carries."""

    item_id: int
    name: str
    category: str
    #: Where this row came from, when it is not simply "the workbook says so" —
    #: e.g. an id the workbook cannot express (0x5c5f 八咫镜[武士], see
    #: ``tools/build_affix_db.py``).  Empty for plain 物品总目录 rows.
    source: str = ""

    @property
    def label(self) -> str:
        """``0x4987 八尺琼勾玉[武士]``."""
        return f"{self.item_id:#06x} {self.name}"


class ItemDb:
    """Name lookup for the item id an accessory record carries (display only).

    A v2.21 record's header field at ``+0x00`` (mirrored at ``+0x02``) holds the
    *item* id, not the captured category type: measured on the reference save's
    save, 212 of 213 accessories resolve to a 饰品 row of 物品总目录.  This table
    answers "which accessory is this?", and — like :class:`GraceDb` — never
    decides what may be written.  A missing table degrades to "no names".
    """

    __slots__ = ("_entries", "_by_id", "catalog_path", "error")

    def __init__(
        self,
        entries: list[ItemEntry] | None = None,
        catalog_path: Path = DEFAULT_ITEM_CATALOG,
        *,
        error: str = "",
    ) -> None:
        self.catalog_path = catalog_path
        self.error = error
        self._entries = tuple(entries) if entries is not None else ()
        by_id: dict[int, ItemEntry] = {}
        for entry in self._entries:
            by_id.setdefault(entry.item_id, entry)
        self._by_id = by_id

    @classmethod
    def from_file(cls, catalog_path: Path = DEFAULT_ITEM_CATALOG) -> "ItemDb":
        return cls(load_item_catalog(catalog_path), catalog_path)

    @classmethod
    def best_effort(cls, catalog_path: Path | None = None) -> "ItemDb":
        """Load the table, or return an empty one carrying the reason."""
        path = DEFAULT_ITEM_CATALOG if catalog_path is None else catalog_path
        try:
            return cls.from_file(path)
        except AffixError as error:
            return cls(catalog_path=path, error=str(error))

    @property
    def is_loaded(self) -> bool:
        return bool(self._entries)

    def __len__(self) -> int:
        return len(self._entries)

    def __contains__(self, item_id: object) -> bool:
        return item_id in self._by_id

    def lookup(self, item_id: int) -> ItemEntry | None:
        return self._by_id.get(item_id)

    def describe(self, item_id: int) -> str | None:
        """``八尺琼勾玉[武士]`` — ``None`` when the id is not in the table."""
        entry = self.lookup(item_id)
        return None if entry is None else entry.name

    def category_of(self, item_id: int) -> str | None:
        """中类 of an item (``武士饰品``/``忍者饰品``), or ``None`` if unknown.

        Evidence for the 改种类 rule: only items of the same 中类 may be swapped,
        and an id that is not in the table (or whose row has no 中类) cannot be
        shown to be in the same 中类, so it can never take part in a swap.
        """
        entry = self.lookup(item_id)
        if entry is None or not entry.category:
            return None
        return entry.category

    def all(self) -> tuple[ItemEntry, ...]:
        return self._entries

    def categories(self) -> tuple[str, ...]:
        seen: list[str] = []
        for entry in self._entries:
            if entry.category not in seen:
                seen.append(entry.category)
        return tuple(seen)

    def labels(self) -> tuple[str, ...]:
        """``0x4987 八尺琼勾玉[武士]`` for every row, for comboboxes."""
        return tuple(entry.label for entry in self._entries)

    def search(self, keyword: str, *, limit: int = 0) -> tuple[AffixEntry, ...]:
        """Every entry whose name, category or id text contains ``keyword``.

        Typing a keyword must never silently pick an affix: the caller shows the
        whole match list (which may be empty, one, or many) and the user chooses.
        A blank keyword matches nothing, so an empty search box cannot be mistaken
        for "everything".
        """
        text = keyword.strip().lower()
        if not text:
            return ()
        compact = text.replace(" ", "")
        matches = [
            entry for entry in self._entries
            if text in entry.name.lower() or text in entry.category.lower()
            or compact in entry.name.lower().replace(" ", "")
            or compact in f"{entry.effect_id:#06x}".lower()
            or compact in f"{entry.effect_id:#x}".lower()
        ]
        if limit > 0:
            return tuple(matches[:limit])
        return tuple(matches)


    def search(self, keyword: str, *, limit: int = 0) -> tuple[ItemEntry, ...]:
        """Item rows whose name or category contains ``keyword`` (filtering)."""
        text = keyword.strip().lower()
        if not text:
            return ()
        matches = [entry for entry in self._entries
                   if text in entry.name.lower() or text in entry.category.lower()]
        return tuple(matches[:limit]) if limit > 0 else tuple(matches)

    def items_in_category(self, category: str | None) -> tuple[ItemEntry, ...]:
        """Every row of one 中类 (``None``/blank means "no filter")."""
        if not category:
            return self._entries
        return tuple(entry for entry in self._entries
                     if entry.category == category)


def load_item_catalog(path: Path = DEFAULT_ITEM_CATALOG) -> list[ItemEntry]:
    """Load the 饰品 item table (display only, never used for legality)."""
    payload = _load_payload(path, "物品种类表", list_key="items")
    entries: list[ItemEntry] = []
    for index, item in enumerate(payload["items"]):
        where = f"第 {index + 1} 条"
        if not isinstance(item, dict):
            raise AffixError(f"{where}: 物品条目必须是对象")
        name = item.get("name")
        category = item.get("category")
        if not isinstance(name, str) or not name.strip():
            raise AffixError(f"{where}: 缺少物品名称")
        if not isinstance(category, str):
            raise AffixError(f"{where}: 缺少物品分类")
        source = item.get("source", "")
        if not isinstance(source, str):
            raise AffixError(f"{where}: source 必须是字符串")
        entries.append(
            ItemEntry(
                item_id=_require_uint32(item, "item_id", where),
                name=name.strip(),
                category=category.strip(),
                source=source.strip(),
            )
        )
    return entries


def save_item_catalog(
    entries: list[ItemEntry],
    path: Path = DEFAULT_ITEM_CATALOG,
    *,
    source: str = "",
    conflicts: list[str] | None = None,
    schema: str = ITEM_CATALOG_SCHEMA,
    default_source: str = "仁王3词条装备库v2.21.xlsx / 物品总目录（饰品）",
) -> None:
    """Write an item table (same envelope, its own ``items`` list)."""
    seen: set[int] = set()
    for entry in entries:
        if entry.item_id in seen:
            raise AffixError(f"拒绝写出含重复物品 ID 的表：{entry.item_id:#x}")
        seen.add(entry.item_id)
    payload = {
        "schema": schema,
        "count": len(entries),
        "source": source or default_source,
        "conflicts": conflicts or [],
        "items": [
            {"item_id": entry.item_id, "name": entry.name,
             "category": entry.category,
             **({"source": entry.source} if entry.source else {})}
            for entry in entries
        ],
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
                    encoding="utf-8", newline="\n")


class GraceDb:
    """Name lookup for the 恩宠/套装 ids that end an accessory's affix list.

    Display only: :class:`AffixDb` still decides what may be *written*.  Missing
    or unreadable table degrades to "no names" instead of failing the app, so a
    user who never regenerated the data still gets the earlier wording.
    """

    __slots__ = ("_entries", "_by_id", "catalog_path", "error")

    def __init__(
        self,
        entries: list[AffixEntry] | None = None,
        catalog_path: Path = DEFAULT_GRACE_CATALOG,
        *,
        error: str = "",
    ) -> None:
        self.catalog_path = catalog_path
        self.error = error
        self._entries = tuple(entries) if entries is not None else ()
        by_id: dict[int, AffixEntry] = {}
        for entry in self._entries:
            by_id.setdefault(entry.effect_id, entry)
        self._by_id = by_id

    @classmethod
    def from_file(cls, catalog_path: Path = DEFAULT_GRACE_CATALOG) -> "GraceDb":
        return cls(load_grace_catalog(catalog_path), catalog_path)

    @classmethod
    def best_effort(cls, catalog_path: Path | None = None) -> "GraceDb":
        """Load the table, or return an empty one carrying the reason."""
        path = DEFAULT_GRACE_CATALOG if catalog_path is None else catalog_path
        try:
            return cls.from_file(path)
        except AffixError as error:
            return cls(catalog_path=path, error=str(error))

    @property
    def is_loaded(self) -> bool:
        return bool(self._entries)

    def __len__(self) -> int:
        return len(self._entries)

    def __contains__(self, effect_id: object) -> bool:
        return effect_id in self._by_id

    def lookup(self, effect_id: int) -> AffixEntry | None:
        return self._by_id.get(effect_id)

    def describe(self, effect_id: int) -> str | None:
        """``稻荷神的恩宠（恩宠）`` — ``None`` when the id is not in the table."""
        entry = self.lookup(effect_id)
        if entry is None:
            return None
        if entry.category:
            return f"{entry.name}（{entry.category}）"
        return entry.name

    def of_kind(self, *kinds: str) -> tuple[AffixEntry, ...]:
        """Entries whose 归属 is one of ``kinds`` (e.g. 恩宠 / 上位恩宠)."""
        return tuple(entry for entry in self._entries if entry.category in kinds)

    def grace_entries(self) -> tuple[AffixEntry, ...]:
        """Only the changeable 恩宠/上位恩宠 entries (never the 套装 ones)."""
        return self.of_kind(*GRACE_KINDS)

    def labels(self) -> tuple[str, ...]:
        """Combo-box labels for the changeable 恩宠: ``0x4fa3 稻荷神的恩宠（恩宠）``."""
        return tuple(f"{entry.effect_id:#06x} {entry.name}（{entry.category}）"
                     for entry in self.grace_entries())

    def all(self) -> tuple[AffixEntry, ...]:
        return self._entries
